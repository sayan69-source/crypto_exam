# 1. Deterministic randomness
#
# Python's `random` is seedable but its internal algorithms are not contractually
# stable across versions. Every centre must derive the IDENTICAL paper from the
# same beacon, so we use an explicit HMAC-SHA256 counter-mode PRNG: fully
# specified, reproducible on any platform, any language, forever.
#
# This mirrors the HKDF construction already used in question-crypto.ts.
# ══════════════════════════════════════════════════════════════════════════════


class DeterministicRNG:
    """HMAC-SHA256 counter-mode PRNG. Byte-identical output for a given seed."""

    def __init__(self, seed: bytes, info: bytes = b"") -> None:
        self._key = hmac.new(seed, b"cryptoexam:prng:" + info, hashlib.sha256).digest()
        self._counter = 0
        self._buf = b""

    def _refill(self) -> None:
        self._buf += hmac.new(
            self._key, self._counter.to_bytes(8, "big"), hashlib.sha256
        ).digest()
        self._counter += 1

    def bytes(self, n: int) -> bytes:
        while len(self._buf) < n:
            self._refill()
        out, self._buf = self._buf[:n], self._buf[n:]
        return out

    def below(self, n: int) -> int:
        """Uniform int in [0, n). Rejection-sampled, so no modulo bias."""
        if n <= 0:
            raise ValueError("n must be positive")
        bits = max(1, (n - 1).bit_length())
        nbytes = (bits + 7) // 8
        mask = (1 << bits) - 1
        while True:
            v = int.from_bytes(self.bytes(nbytes), "big") & mask
            if v < n:
                return v

    def shuffled(self, items: Iterable[Any]) -> list[Any]:
        """Fisher-Yates. Deterministic given the seed."""
        arr = list(items)
        for i in range(len(arr) - 1, 0, -1):
            j = self.below(i + 1)
            arr[i], arr[j] = arr[j], arr[i]
        return arr


def hkdf_seed(beacon: bytes, purpose: str, exam_id: str) -> bytes:
    """Mirrors question-crypto.ts: HKDF-ish derivation from the T0 beacon."""
    return hmac.new(
        beacon, f"cryptoexam:{purpose}:{exam_id}".encode(), hashlib.sha256
    ).digest()


