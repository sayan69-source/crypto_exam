# 3. Item templates  (design doc section 5.1)
# ══════════════════════════════════════════════════════════════════════════════


@dataclass(frozen=True)
class Distractor:
    expr: str
    misconception: str


@dataclass
class Template:
    """
    An item MODEL. Expands into many sibling items whose keys are computed.

    `answer_expr` and every distractor expression are evaluated independently at
    expansion time; the resulting item carries no model-asserted answer at all.
    """
    template_id: str
    author: str            # setter id - drives the anti-leak contribution cap
    subject: str
    topic: str
    blooms: int            # 1..6
    stem: str              # "...radius {R} m ... speed {v} m/s..."
    params: dict[str, list[Any]]
    answer_expr: str
    distractors: list[Distractor]
    unit: str = ""
    irt_a: float = 1.0     # discrimination - a template-family prior
    irt_b: float = 0.0     # difficulty     - siblings inherit, +- jitter
    irt_c: float = 0.25    # guessing       - 1/4 for 4-option MCQ
    param_constraint: Callable[[dict[str, Any]], bool] | None = None

    def combinations(self) -> list[dict[str, Any]]:
        keys = sorted(self.params)  # sorted => deterministic expansion order
        out = []
        for values in product(*(self.params[k] for k in keys)):
            combo = dict(zip(keys, values))
            if self.param_constraint is None or self.param_constraint(combo):
                out.append(combo)
        return out


@dataclass
class Item:
    """A concrete, machine-verified question. Ready to be sealed."""
    item_id: str
    template_id: str
    author: str
    subject: str
    topic: str
    blooms: int
    stem: str
    options: list[str]
    correct_index: int
    irt_a: float
    irt_b: float
    irt_c: float
    status: str = "PROVISIONAL"     # PROVISIONAL | CALIBRATED | RETIRED
    provenance: dict[str, Any] = field(default_factory=dict)

    def information(self, theta: float) -> float:
        """3PL Fisher information at ability theta. The unit of 'how hard'."""
        a, b, c = self.irt_a, self.irt_b, self.irt_c
        p = c + (1.0 - c) / (1.0 + math.exp(-a * (theta - b)))
        q = 1.0 - p
        if p <= 1e-9 or q <= 1e-9:
            return 0.0
        return (a * a) * (q / p) * (((p - c) / (1.0 - c)) ** 2)


def _fmt(value: float, unit: str) -> str:
    """Render a number the way a candidate would see it."""
    text = f"{value:.4f}".rstrip("0").rstrip(".") if value % 1 else str(int(value))
    return f"{text} {unit}".strip()


