def build_pool(quiet: bool) -> list[Item]:
    templates = demo_templates() + [planted_bad_template()]
    rng = DeterministicRNG(b"pool-expansion-seed-v1")
    report = expand_and_verify(templates, rng, max_variants_per_template=12)

    for item in report.accepted:
        item.status = "CALIBRATED"   # in reality: earned via design doc section 7

    if not quiet:
        print("=" * 78)
        print("STAGE 1 - TEMPLATE EXPANSION + MACHINE VERIFICATION")
        print("=" * 78)
        print(f"  templates in            : {len(templates)}")
        print(f"  items accepted          : {len(report.accepted)}")
        print(f"  items rejected          : {len(report.rejected)}")
        print()
        print("  Rejections (each one is a wrong answer key that never shipped):")
        shown: set[str] = set()
        for ident, reason in report.rejected:
            family = ident.split("#")[0]
            if family in shown:
                continue
            shown.add(family)
            print(f"    {ident:26s} {reason[:88]}")
        print()
        sample = report.accepted[0]
        print("  Sample verified item:")
        print(f"    id       : {sample.item_id}")
        print(f"    stem     : {sample.stem[:96]}")
        print(f"    options  : {sample.options}")
        print(f"    key      : option {sample.correct_index} = {sample.options[sample.correct_index]}")
        print(f"    derived  : {sample.provenance['derivation']}  with  {sample.provenance['params']}")
        print("    ^ the key was COMPUTED from this expression, not asserted by a model")
        print()

    return report.accepted


def demo(quiet: bool) -> int:
    failures: list[str] = []

    pool = build_pool(quiet)

    bp = Blueprint(
        exam_id=EXAM_ID,
        length=18,
        per_subject={"Physics": 7, "Chemistry": 6, "Mathematics": 5},
        max_per_author_pct=0.11,       # 2 of 18 - see the scale note in the summary
        # A selection exam wants its measurement precision concentrated near the
        # CUT SCORE, not at average ability - hence the peak at theta = +1.0.
        # Magnitudes are sized to what an 18-item form can actually deliver; a
        # 90-item paper carries ~5x this information.
        target_information={-3.0: 0.05, -2.0: 0.30, -1.0: 1.30, 0.0: 3.40,
                            1.0: 4.20, 2.0: 2.10, 3.0: 0.70},
    )

    # ---- CLAIM 1: no hallucinated key survived -------------------------------
    if any(i.template_id.startswith("BAD-") for i in pool):
        failures.append("CLAIM 1 FAILED: a hallucinated item reached the pool")

    # ---- CLAIM 2: determinism + unpredictability -----------------------------
    form_a1 = assemble(pool, bp, BEACON_A)
    form_a2 = assemble(pool, bp, BEACON_A)
    form_b = assemble(pool, bp, BEACON_B)

    hash_a1, hash_a2, hash_b = map(form_manifest_hash, (form_a1, form_a2, form_b))

    if hash_a1 != hash_a2:
        failures.append("CLAIM 2 FAILED: same beacon produced different papers")
    if hash_a1 == hash_b:
        failures.append("CLAIM 2 FAILED: different beacons produced the same paper")

    overlap = len({i.item_id for i in form_a1} & {i.item_id for i in form_b})

    if not quiet:
        print("=" * 78)
        print("STAGE 2 - BEACON-DRIVEN ASSEMBLY  (nobody chose these questions)")
        print("=" * 78)
        print(f"  pool size               : {len(pool)} calibrated items")
        print(f"  paper length            : {bp.length}")
        print(f"  blueprint               : {bp.per_subject}")
        print(f"  author cap              : {bp.max_per_author()} items per setter")
        print()
        print(f"  beacon A -> manifest    : {hash_a1[:32]}...")
        print(f"  beacon A -> manifest    : {hash_a2[:32]}...   (re-run, must match)")
        print(f"  beacon B -> manifest    : {hash_b[:32]}...   (must differ)")
        print()
        print(f"  determinism             : {'PASS' if hash_a1 == hash_a2 else 'FAIL'}"
              "   same beacon => byte-identical paper at every centre")
        print(f"  unpredictability        : {'PASS' if hash_a1 != hash_b else 'FAIL'}"
              "   different beacon => different paper")
        print(f"  overlap A vs B          : {overlap}/{bp.length} items")
        print()

    # ---- CLAIM 3: fairness + constraints -------------------------------------
    for label, form in (("A", form_a1), ("B", form_b)):
        problems = check_constraints(form, bp)
        if problems:
            failures.append(f"CLAIM 3 FAILED: form {label} violates: {problems}")

    tif_a, tif_b = _tif(form_a1), _tif(form_b)
    peak = max(max(tif_a.values()), max(tif_b.values()))
    worst_gap = max(abs(tif_a[t] - tif_b[t]) for t in THETA_GRID)
    worst_pct = 100.0 * worst_gap / peak if peak else 0.0

    if worst_pct > 15.0:
        failures.append(
            f"CLAIM 3 FAILED: forms differ by {worst_pct:.1f}% of peak information "
            "- they are not statistically equivalent"
        )

    if not quiet:
        print("=" * 78)
        print("STAGE 3 - FAIRNESS  (are the two papers equally hard?)")
        print("=" * 78)
        print("  Test Information Function - higher means more measurement precision")
        print()
        print(f"  {'ability':>9} {'target':>9} {'form A':>9} {'form B':>9} {'|A-B|':>8}")
        print(f"  {'-'*9} {'-'*9} {'-'*9} {'-'*9} {'-'*8}")
        for t in THETA_GRID:
            print(f"  {t:>+9.1f} {bp.target_information.get(t, 0):>9.2f} "
                  f"{tif_a[t]:>9.2f} {tif_b[t]:>9.2f} {abs(tif_a[t]-tif_b[t]):>8.2f}")
        print()
        print(f"  worst divergence        : {worst_gap:.3f} ({worst_pct:.1f}% of peak)")
        print(f"  equivalence (<15%)      : {'PASS' if worst_pct <= 15.0 else 'FAIL'}")
        print()

        print("  Anti-leak - setter contribution to each form:")
        for label, form in (("A", form_a1), ("B", form_b)):
            counts: dict[str, int] = {}
            for item in form:
                counts[item.author] = counts.get(item.author, 0) + 1
            worst_author = max(counts, key=lambda a: counts[a])
            worst_n = counts[worst_author]
            print(f"    form {label}: {dict(sorted(counts.items()))}")
            print(f"             worst case {worst_author} = {worst_n}/{bp.length} "
                  f"({100.0*worst_n/bp.length:.1f}% of the paper)")
        print()
        print("  ^ A setter who leaks EVERYTHING they ever wrote compromises at most")
        print("    this fraction of the paper. That is the anti-leak guarantee, and it")
        print("    is a hard constraint in the optimiser rather than a policy promise.")
        print()

        print("=" * 78)
        print("ASSEMBLED PAPER (form A)")
        print("=" * 78)
        for n, item in enumerate(form_a1, 1):
            print(f"  Q{n:02d} [{item.subject[:4]:4s}/{item.author}] {item.stem[:82]}")
        print()

    # ---- verdict --------------------------------------------------------------
    print("=" * 78)
    if failures:
        print("RESULT: FAILED")
        for f in failures:
            print(f"  - {f}")
        print("=" * 78)
        return 1

    print("RESULT: ALL CLAIMS HOLD")
    print("=" * 78)
    print("  1. ANTI-HALLUCINATION  every key computed and re-verified; the planted")
    print("                         hallucinated item was rejected before the pool")
    print("  2. ANTI-LEAK           the paper is a function of a beacon that did not")
    print("                         exist when the items were written; no setter, no")
    print("                         operator and no centre could have known it")
    print("  3. FAIRNESS            independently assembled forms carry equivalent")
    print("                         information; blueprint and setter caps hold on all")
    print("=" * 78)
    print()
    print("NOTE ON DEMO SCALE: ~200 items from 25 templates across 12 setters, so the")
    print("cap sits at 11% (2 of 18). Production targets 10,000 items / 400+ templates /")
    print("50+ setters, where the cap tightens to 5% - 4 items on a 90-item paper, and")
    print("A-vs-B overlap falls toward zero. Scaling the pool strengthens every number")
    print("here; no part of the mechanism changes.")
    return 0


