# 5. Automated Test Assembly  (design doc section 6.1)
#
# Beacon-seeded, constraint-respecting, deterministic. This is the function that
# replaces "a human picks the questions".
# ══════════════════════════════════════════════════════════════════════════════

THETA_GRID = [-3.0, -2.0, -1.0, 0.0, 1.0, 2.0, 3.0]


@dataclass
class Blueprint:
    exam_id: str
    length: int
    per_subject: dict[str, int]
    blooms_min: dict[int, int] = field(default_factory=dict)
    max_per_author_pct: float = 0.05      # design doc section 5.3 - the anti-leak cap
    target_information: dict[float, float] = field(default_factory=dict)

    def max_per_author(self) -> int:
        return max(1, math.ceil(self.length * self.max_per_author_pct))


def _tif(items: list[Item]) -> dict[float, float]:
    return {t: sum(i.information(t) for i in items) for t in THETA_GRID}


def _misfit(items: list[Item], target: dict[float, float]) -> float:
    """L1 distance between this form's information curve and the target."""
    cur = _tif(items)
    return sum(abs(cur[t] - target.get(t, 0.0)) for t in THETA_GRID)


class AssemblyError(Exception):
    pass


def assemble(pool: list[Item], bp: Blueprint, beacon: bytes) -> list[Item]:
    """
    Select `bp.length` items from `pool`, seeded by the T0 beacon.

    Randomised-greedy (GRASP): at each step consider the top-k candidates by
    marginal improvement to the information curve and pick among them using the
    beacon PRNG. Near-optimal on fairness, genuinely unpredictable in selection.

    Hard constraints, all enforced at insertion time:
      * exact per-subject counts (blueprint)
      * <= max_per_author items from any one setter   <- the anti-leak guarantee
      * <= 1 item from any one template               <- no sibling collisions
      * only CALIBRATED items may be selected         <- nothing unproven is scored
    """
    rng = DeterministicRNG(hkdf_seed(beacon, "ata", bp.exam_id))

    eligible = [i for i in pool if i.status == "CALIBRATED"]
    if len(eligible) < bp.length:
        raise AssemblyError(
            f"pool too small: {len(eligible)} calibrated items, need {bp.length}"
        )

    # ---- feasibility pre-check ------------------------------------------------
    # "<= 1 item per template" caps a form at (number of distinct templates), and
    # the author cap caps it at (setters x cap). Catch an impossible blueprint here
    # with a diagnostic rather than 3/4 of the way through a greedy run.
    cap = bp.max_per_author()
    for subject, want in bp.per_subject.items():
        subject_items = [i for i in eligible if i.subject == subject]
        n_templates = len({i.template_id for i in subject_items})
        n_authors = len({i.author for i in subject_items})
        if n_templates < want:
            raise AssemblyError(
                f"infeasible blueprint: subject {subject!r} needs {want} items but the "
                f"pool has only {n_templates} distinct templates, and no form may carry "
                "two siblings of the same template. Author more templates or shorten "
                "the paper."
            )
        if n_authors * cap < want:
            raise AssemblyError(
                f"infeasible blueprint: subject {subject!r} needs {want} items but has "
                f"{n_authors} setters at a cap of {cap} each (max {n_authors * cap}). "
                "Recruit more setters for this subject or relax max_per_author_pct."
            )
    if sum(bp.per_subject.values()) != bp.length:
        raise AssemblyError(
            f"blueprint subject counts sum to {sum(bp.per_subject.values())}, "
            f"not the paper length {bp.length}"
        )

    # Beacon-shuffled base order: this is what makes two different beacons
    # produce genuinely different papers rather than the same greedy answer.
    eligible = rng.shuffled(sorted(eligible, key=lambda i: i.item_id))

    chosen: list[Item] = []
    by_subject: dict[str, int] = {s: 0 for s in bp.per_subject}
    by_author: dict[str, int] = {}
    used_templates: set[str] = set()
    author_cap = bp.max_per_author()

    def admissible(item: Item) -> bool:
        if item.template_id in used_templates:
            return False
        if by_author.get(item.author, 0) >= author_cap:
            return False
        if by_subject.get(item.subject, 0) >= bp.per_subject.get(item.subject, 0):
            return False
        return True

    for _ in range(bp.length):
        candidates = [i for i in eligible if admissible(i)]
        if not candidates:
            raise AssemblyError(
                "no admissible item remains - constraints are infeasible for this pool. "
                f"chosen={len(chosen)}/{bp.length}, subject counts={by_subject}"
            )

        # Rank by how much each candidate closes the gap to the target curve.
        scored = sorted(
            ((_misfit(chosen + [c], bp.target_information), c.item_id, c) for c in candidates),
            key=lambda row: (row[0], row[1]),      # deterministic tie-break by id
        )
        shortlist = scored[: min(5, len(scored))]  # GRASP restricted candidate list
        _, _, pick = shortlist[rng.below(len(shortlist))]

        chosen.append(pick)
        by_subject[pick.subject] = by_subject.get(pick.subject, 0) + 1
        by_author[pick.author] = by_author.get(pick.author, 0) + 1
        used_templates.add(pick.template_id)

    # Present in a beacon-determined order (per-form; per-SEAT scrambling on top
    # of this is what defeats neighbour-copying - design doc section 6.4).
    return rng.shuffled(chosen)


def form_manifest_hash(form: list[Item]) -> str:
    """
    What gets anchored on-chain. Order-independent so it commits to the SET of
    items, letting per-seat scrambling vary freely underneath the commitment.
    """
    payload = json.dumps(sorted(i.item_id for i in form), separators=(",", ":"))
    return hashlib.sha256(payload.encode()).hexdigest()


def check_constraints(form: list[Item], bp: Blueprint) -> list[str]:
    """Independent re-verification. This is what an auditor runs (design doc 6.1)."""
    problems: list[str] = []

    if len(form) != bp.length:
        problems.append(f"length {len(form)} != {bp.length}")

    subjects: dict[str, int] = {}
    authors: dict[str, int] = {}
    templates: dict[str, int] = {}
    for item in form:
        subjects[item.subject] = subjects.get(item.subject, 0) + 1
        authors[item.author] = authors.get(item.author, 0) + 1
        templates[item.template_id] = templates.get(item.template_id, 0) + 1

    for subject, want in bp.per_subject.items():
        got = subjects.get(subject, 0)
        if got != want:
            problems.append(f"subject {subject}: {got} != {want}")

    cap = bp.max_per_author()
    for author, count in authors.items():
        if count > cap:
            problems.append(f"AUTHOR CAP BREACH: {author} has {count} items (cap {cap})")

    for tid, count in templates.items():
        if count > 1:
            problems.append(f"sibling collision: {tid} appears {count} times")

    for item in form:
        if item.status != "CALIBRATED":
            problems.append(f"uncalibrated item scored: {item.item_id}")

    return problems


