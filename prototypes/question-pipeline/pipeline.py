# 4. Expansion + verification  (design doc section 5.2, stages S0 and S1)
# ══════════════════════════════════════════════════════════════════════════════


@dataclass
class ExpansionReport:
    accepted: list[Item] = field(default_factory=list)
    rejected: list[tuple[str, str]] = field(default_factory=list)  # (id, reason)

    def reject(self, ident: str, reason: str) -> None:
        self.rejected.append((ident, reason))


def expand_and_verify(
    templates: list[Template],
    rng: DeterministicRNG,
    max_variants_per_template: int = 12,
) -> ExpansionReport:
    """
    Expand every template into sibling items, verifying each one.

    S0 (structural): 4 distinct options, key present exactly once, key position
                     balanced across the pool, stem fully substituted.
    S1 (symbolic):   the correct answer is RE-DERIVED from the expression. An
                     item can only exist if its key is reproducible.
    """
    report = ExpansionReport()

    for tpl in templates:
        combos = tpl.combinations()
        if not combos:
            report.reject(tpl.template_id, "no parameter combination satisfies constraints")
            continue

        # Deterministic subsample so pools stay a sane size.
        combos = rng.shuffled(combos)[:max_variants_per_template]

        for idx, combo in enumerate(combos):
            ident = f"{tpl.template_id}#{idx:02d}"
            try:
                # ---- S1: compute the key. Never trust an asserted answer. ----
                answer = verify_expression(tpl.answer_expr, combo)
                wrongs = [verify_expression(d.expr, combo) for d in tpl.distractors]

                # ---- S0: structural integrity ----
                if len(tpl.distractors) != 3:
                    raise VerificationError("expected exactly 3 distractors")

                rendered = [_fmt(answer, tpl.unit)] + [_fmt(w, tpl.unit) for w in wrongs]
                if len(set(rendered)) != 4:
                    raise VerificationError(
                        "a distractor collides with the key or another distractor "
                        f"(rendered: {rendered})"
                    )

                stem = tpl.stem
                for key, value in combo.items():
                    stem = stem.replace("{" + key + "}", str(value))
                if "{" in stem or "}" in stem:
                    raise VerificationError(f"stem has unsubstituted placeholders: {stem!r}")

                # ---- key position balanced by the beacon PRNG, not by habit ----
                order = rng.shuffled(range(4))
                options = [rendered[i] for i in order]
                correct_index = order.index(0)

                # Siblings inherit the family's IRT prior with a small deterministic
                # jitter, so they are near-identical but not literally identical.
                jitter = (rng.below(2001) - 1000) / 10000.0   # +-0.10 logits

                report.accepted.append(
                    Item(
                        item_id=ident,
                        template_id=tpl.template_id,
                        author=tpl.author,
                        subject=tpl.subject,
                        topic=tpl.topic,
                        blooms=tpl.blooms,
                        stem=stem,
                        options=options,
                        correct_index=correct_index,
                        irt_a=tpl.irt_a,
                        irt_b=tpl.irt_b + jitter,
                        irt_c=tpl.irt_c,
                        provenance={"params": combo, "derivation": tpl.answer_expr},
                    )
                )
            except VerificationError as exc:
                report.reject(ident, str(exc))

    return report


