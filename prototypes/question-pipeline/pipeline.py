# 2. Safe expression evaluation
#
# Templates carry an expression for the correct answer and for each distractor.
# We evaluate in a locked-down namespace: no builtins, no attribute access, no
# names outside the declared parameters and a small maths allow-list.
#
# In production this is SymPy doing genuine symbolic re-derivation. The point of
# the stage is identical either way: THE KEY IS COMPUTED, NOT ASSERTED.
# ══════════════════════════════════════════════════════════════════════════════

_ALLOWED_NAMES = {
    "sqrt": math.sqrt, "pi": math.pi, "e": math.e, "log": math.log,
    "exp": math.exp, "sin": math.sin, "cos": math.cos, "tan": math.tan,
    "abs": abs, "min": min, "max": max, "round": round,
}
_EXPR_OK = re.compile(r"^[0-9a-zA-Z_+\-*/%.,()\s]+$")


class VerificationError(Exception):
    """Raised when an item fails machine verification. Item is discarded."""


def verify_expression(expr: str, params: dict[str, Any]) -> float:
    """Evaluate `expr` against `params`. Rejects anything outside the allow-list."""
    if not _EXPR_OK.match(expr):
        raise VerificationError(f"expression contains disallowed characters: {expr!r}")
    if "__" in expr:
        raise VerificationError("dunder access is not permitted")
    env: dict[str, Any] = {"__builtins__": {}}
    env.update(_ALLOWED_NAMES)
    overlap = set(params) & set(_ALLOWED_NAMES)
    if overlap:
        raise VerificationError(f"parameter shadows a builtin: {sorted(overlap)}")
    env.update(params)
    try:
        value = eval(expr, env)  # noqa: S307 - namespace is locked down above
    except Exception as exc:  # noqa: BLE001
        raise VerificationError(f"evaluation failed for {expr!r}: {exc}") from exc
    if not isinstance(value, (int, float)) or isinstance(value, bool):
        raise VerificationError(f"expression is not numeric: {expr!r} -> {value!r}")
    if math.isnan(value) or math.isinf(value):
        raise VerificationError(f"expression is not finite: {expr!r}")
    return float(value)


