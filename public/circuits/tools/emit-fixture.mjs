#!/usr/bin/env node
/**
 * Emit a real Groth16 proof as a test fixture for the Solidity verifier.
 *
 * The contract tests need a proof the on-chain verifier actually accepts —
 * inventing one is exactly the failure mode `submitZKProof` used to have. This
 * writes a genuine proof (and a deliberately corrupted twin, so the tests can
 * show a bad proof is rejected) in the calldata shape Solidity expects.
 *
 *   node tools/emit-fixture.mjs > ../contracts/test/fixtures/zk-proof.json
 */
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import * as snarkjs from "snarkjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const BUILD = join(HERE, "..", "build");
const B_OFFSET = 4000; // see tools/selftest.mjs
const N = 6;

const enc = Array.from({ length: N }, (_, i) => String(1000003n * BigInt(i + 1)));

const mod = await import(
  pathToFileURL(join(BUILD, "poseidon_commit_js", "witness_calculator.js")).href
);
const wc = await (mod.default ?? mod)(
  readFileSync(join(BUILD, "poseidon_commit_js", "poseidon_commit.wasm")),
);
const committed = (await wc.calculateWitness({ question_enc: enc }, true))[1].toString();

const input = {
  irt_b: Array.from({ length: N }, (_, i) => String(B_OFFSET + (i - 4) * 100)),
  irt_a: Array.from({ length: N }, () => "1200"),
  irt_c: Array.from({ length: N }, () => "200"),
  question_enc: enc,
  committed_hash: committed,
  target_mean_b: String(B_OFFSET),
  min_a: "800",
  max_c: "250",
  tolerance: "500",
};

const { proof, publicSignals } = await snarkjs.groth16.fullProve(
  input,
  join(BUILD, "difficulty_proof_js", "difficulty_proof.wasm"),
  join(BUILD, "difficulty_proof_final.zkey"),
);

// Solidity calldata order: π_b's G2 coordinates are transposed relative to snarkjs.
const solidity = {
  a: [proof.pi_a[0], proof.pi_a[1]],
  b: [
    [proof.pi_b[0][1], proof.pi_b[0][0]],
    [proof.pi_b[1][1], proof.pi_b[1][0]],
  ],
  c: [proof.pi_c[0], proof.pi_c[1]],
  publicSignals,
};

// A proof that is well-formed but wrong: one field element of π_a nudged. The
// pairing check must reject it.
const forged = structuredClone(solidity);
forged.a[0] = (BigInt(forged.a[0]) + 1n).toString();

process.stdout.write(
  JSON.stringify(
    {
      _comment:
        "Generated by circuits/tools/emit-fixture.mjs from difficulty_proof_final.zkey. " +
        "Regenerate whenever the circuit or the proving key changes.",
      valid: solidity,
      forged,
    },
    null,
    2,
  ) + "\n",
);

// snarkjs leaves its worker pool running, so the process never exits on its own.
process.exit(0);
